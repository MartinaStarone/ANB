def xtime(a):
    return (((a<<1)^0x1B)&0xFF) if (a & 0x80) else (a<<1)
def mult2(a):
    return xtime(a)
def mult3(a):
    return xtime(a)^a

def delta_s(c_byte, key, c_tilde, faulty_val = 0):
    s_corretto = rsbox[c_byte^ key]
    s_corrotto= rsbox[c_tilde ^ key ^ faulty_val]

    delta_s12 = s_corretto ^ s_corrotto

    return delta_s12

